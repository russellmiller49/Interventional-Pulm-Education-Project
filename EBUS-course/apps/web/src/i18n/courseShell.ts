function getCourseShellOverlay(locale: AppLocale) {
  return courseShellOverlays[locale] ?? null;
}

export function localizeShellText(source: string, locale: AppLocale): string {
  if (locale === 'en') {
    return source;
  }

  return shellText[locale][source] ?? source;
}

export function getLocalizedCourseInfo(locale: AppLocale): CourseInfoContent {
  const overlay = getCourseShellOverlay(locale)?.['content/course/course-info.json'];

  return mergeLocalizedValue(courseInfo, overlay);
}

export function getLocalizedWelcomeLecture(locale: AppLocale): LectureManifestItem {
  const overlay = getCourseShellOverlay(locale)?.['content/course/welcome.json'];

  return mergeLocalizedValue(welcomeLecture, overlay);
}

export function getLocalizedModuleContent(locale: AppLocale): ModuleContent[] {
  const overlay = getCourseShellOverlay(locale)?.['content/modules/modules.json'];

  return mergeLocalizedValue(moduleContent, overlay);
}

export function getLocalizedHomeModuleCards(locale: AppLocale): AppModuleCard[] {
  const localizedModules = getLocalizedModuleContent(locale);
  const moduleLookup = new Map(localizedModules.map((entry) => [entry.id, entry]));
  const stationMap = moduleLookup.get('station-map');

  return homeModuleCards.map((card) => {
    const moduleId = routeModuleMap[card.id];
    const localizedModule = card.id === 'stations' ? stationMap : moduleId ? moduleLookup.get(moduleId) : undefined;

    if (!localizedModule) {
      return {
        ...card,
        title: localizeShellText(card.title, locale),
        description: localizeShellText(card.description, locale),
      };
    }

    return {
      ...card,
      title: localizedModule.title,
      description: localizedModule.summary,
    };
  });
}

export function useCourseShellText() {
  const { locale } = useLocale();

  return useMemo(() => (source: string) => localizeShellText(source, locale), [locale]);
}

