#!/usr/bin/env node
/**
 * Builds the annotated EBUS node images used by EBUS Guided lesson 16 (node characterization).
 *
 * Source: the owner's folder of EBUS stills named for the feature each one shows, with a CVAT
 * "CVAT for images 1.1" export beside them (`annotations 3.xml`: node polygons, distinct and
 * indistinct margin polylines, long and short axes, central hilar structure and coagulation
 * necrosis regions). The folder is not in Git; read it in place:
 *
 *   node scripts/ebus-guided/build-node-feature-images.mjs \
 *     "/Users/russellmiller/Projects/Interventional-Pulm-Education-Project-Personal-Knowlege-Files/EBUS sonographic features"
 *
 * Writes:
 *   public/ebus-guided/node-features/<slug>.jpg          re-encoded, metadata stripped, same pixels
 *   src/features/ebus-guided/content/node-feature-annotations.generated.ts
 *
 * Image size is unchanged, so the annotation coordinates are used as exported. Teaching text,
 * stations and crops live in `content/node-features.ts`, keyed by slug.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'

const DEFAULT_SOURCE =
  '/Users/russellmiller/Projects/Interventional-Pulm-Education-Project-Personal-Knowlege-Files/EBUS sonographic features'
const source = process.argv[2] ?? DEFAULT_SOURCE
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', '..')
const outImages = path.join(root, 'public/ebus-guided/node-features')
const outData = path.join(
  root,
  'src/features/ebus-guided/content/node-feature-annotations.generated.ts',
)

/** Source file name → stable slug. Every annotated image must appear here. */
const SLUGS = {
  '2R small round sharp.png': 'station-2r-round-distinct',
  '4L heterogenous.jpg': 'station-4l-heterogeneous',
  '4R oval with cnetral hilar structure.jpg': 'station-4r-oval-chs',
  '7 coagulation necrosis.jpg': 'station-7-necrosis',
  '7 indistinct margins.jpg': 'station-7-indistinct',
  '7 large round with sharp margins.jpg': 'station-7-round-distinct',
  '7 oval.jpg': 'station-7-oval',
  'homogenous 7.jpg': 'station-7-homogeneous',
}
const LABELS = {
  Lymph_node: 'node',
  Distinct_margin: 'distinct-margin',
  Indistinct_margin: 'indistinct-margin',
  Central_hilar_structure_region: 'chs',
  Coagulation_necrosis_region: 'cns',
  Short_axis: 'short-axis',
  Long_axis: 'long-axis',
}

const xmlPath = path.join(source, 'annotations 3.xml')
if (!existsSync(xmlPath)) throw new Error('No annotations 3.xml in ' + source)
const xml = await readFile(xmlPath, 'utf8')
const attr = (tag, name) => tag.match(new RegExp(name + '="([^"]*)"'))?.[1]
const unescape = (s) => s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')

const images = []
for (const [, open, body] of xml.matchAll(/<image (\b[^>]*)>([\s\S]*?)<\/image>/g)) {
  const name = unescape(attr(open, 'name'))
  const slug = SLUGS[name]
  if (!slug) throw new Error('Annotated image has no slug: ' + name)
  const width = Number(attr(open, 'width'))
  const height = Number(attr(open, 'height'))
  const shapes = []
  for (const [, kind, tag] of body.matchAll(/<(polygon|polyline) (\b[^>]*?)\/?>/g)) {
    const label = LABELS[attr(tag, 'label')]
    if (!label) throw new Error(`Unknown label ${attr(tag, 'label')} on ${name}`)
    const points = attr(tag, 'points')
      .split(';')
      .map((pair) => pair.split(',').map((v) => Math.round(Number(v) * 10) / 10))
    shapes.push({ label, kind, points })
  }
  const file = path.join(source, name)
  const meta = await sharp(file).metadata()
  if (meta.width !== width || meta.height !== height)
    throw new Error(
      `${name}: file is ${meta.width}x${meta.height}, annotations say ${width}x${height}`,
    )
  await mkdir(outImages, { recursive: true })
  await sharp(file)
    .flatten({ background: '#000000' })
    .jpeg({ quality: 86, mozjpeg: true })
    .toFile(path.join(outImages, slug + '.jpg'))
  images.push({ slug, source: name, width, height, shapes })
}
const missing = Object.keys(SLUGS).filter((name) => !images.some((i) => i.source === name))
if (missing.length) throw new Error('Mapped but not annotated: ' + missing.join(', '))

images.sort((a, b) => a.slug.localeCompare(b.slug))
const body = `/* Generated by scripts/ebus-guided/build-node-feature-images.mjs from the owner's CVAT export
 * ("annotations 3.xml" beside the EBUS sonographic-feature stills). Do not edit by hand. */
export type NodeAnnotationLabel =
  | 'node'
  | 'distinct-margin'
  | 'indistinct-margin'
  | 'chs'
  | 'cns'
  | 'short-axis'
  | 'long-axis'
export interface NodeAnnotationShape {
  label: NodeAnnotationLabel
  kind: 'polygon' | 'polyline'
  points: [number, number][]
}
export interface AnnotatedNodeImage {
  slug: string
  source: string
  width: number
  height: number
  shapes: NodeAnnotationShape[]
}
export const NODE_FEATURE_ANNOTATIONS: Record<string, AnnotatedNodeImage> = ${JSON.stringify(
  Object.fromEntries(images.map((i) => [i.slug, i])),
  null,
  2,
)}
`
await writeFile(outData, body)
console.log(
  `Wrote ${images.length} images to ${path.relative(root, outImages)} and ${path.relative(root, outData)}`,
)
