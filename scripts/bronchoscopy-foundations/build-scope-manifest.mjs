/** Format generated JSON before hashing. Never rewrite the independently owned graph. */
import { readFile, writeFile, readdir } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'
import prettier from 'prettier'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const anatomy = path.join(root, 'public/bronchoscopy-foundations/anatomy')
const profile = 'adult-teaching-combined-left-basal-v1'
const options = await prettier.resolveConfig(path.join(root, 'package.json'))
const sha = (bytes) => createHash('sha256').update(bytes).digest('hex')
async function inventory(directory, prefix = '') {
  const paths = []
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const relative = prefix + entry.name
    if (entry.isDirectory())
      paths.push(...(await inventory(path.join(directory, entry.name), relative + '/')))
    else if (entry.isFile() && relative !== 'manifest.json') paths.push(relative)
    else if (!entry.isFile()) throw new Error(`Unexpected non-regular asset: ${relative}`)
  }
  return paths.sort()
}
const paths = await inventory(anatomy)
for (const relative of paths.filter((p) => p.endsWith('.json') && !p.endsWith('/graph.json'))) {
  const filename = path.join(anatomy, relative)
  await writeFile(
    filename,
    await prettier.format(await readFile(filename, 'utf8'), { ...options, parser: 'json' }),
  )
}
const files = []
for (const relative of paths) {
  const teachingProp =
    /^devices\/(bench|findings|handle|scope-tip)\.glb$/.test(relative) ||
    relative === 'devices/teaching-props.json'
  const graph = relative.endsWith('/graph.json')
  const airway = relative.startsWith(profile + '/')
  const larynx = relative.startsWith('larynx/') || relative.includes('larynx-')
  const devices = relative.startsWith('devices/') || relative.endsWith('accessories.png')
  const review = relative.includes('/review/') || relative.startsWith('review/')
  const bytes = await readFile(path.join(anatomy, relative))
  const origin = teachingProp
    ? 'Authored scope handle, distal tip, asymmetric bench target and generic practice geometry; not manufacturer or clinical reference assets'
    : graph
      ? 'Existing case-001 teaching graph; retained without modification'
      : airway
        ? 'Derived from the reviewed case-001 lumen; distal closing caps authored for simulation'
        : larynx
          ? 'Authored laryngeal wall and folds registered to the supplied cartilage/ligament model'
          : devices
            ? 'Authored teaching device dimensions and accessory geometry'
            : 'Generated technical review of the authored and derived scope assets'
  const landmarks = {
    rul: 'RB1 above RB2 and RB3; edge 3 at 10 mm',
    rml: 'RB5 left of RB4; edge 9 at 6 mm',
    lul: 'Upper division above lingula; edge 496 at 9 mm',
  }
  const id = path.basename(relative, '.png')
  files.push({
    path: relative,
    bytes: bytes.length,
    sha256: sha(bytes),
    provenance: {
      class: graph || airway ? 'derived-teaching-case' : 'authored-for-simulation',
      source: graph
        ? [
            'public/airway-anatomy/case-001/metadata/airway_graph.json',
            'public/airway-anatomy/case-001/metadata/centerline_labels.json',
          ]
        : airway
          ? ['public/airway-anatomy/case-001/lumen-v2.glb']
          : larynx
            ? ['anatomy_assets/Larynx.glb']
            : ['scope asset brief; authored geometry parameters'],
      generatedBy: teachingProp
        ? 'scripts/bronchoscopy-foundations/build-teaching-props.py'
        : graph
          ? 'scripts/bronchoscopy-foundations/build-teaching-graph.mts'
          : review
            ? 'scripts/bronchoscopy-foundations/review-scope-assets.mjs'
            : 'scripts/bronchoscopy-foundations/build-scope-assets.py',
      numberClass:
        'Geometry dimensions, morph states, device values, trimming and review settings are authored for simulation unless explicitly identified as measured build results.',
    },
    origin,
    creator_or_rightsholder:
      graph || airway || larynx
        ? 'Source rights holder pending owner confirmation; derived asset generated by repository tooling'
        : 'Authored for this educational module; rights holder pending owner confirmation',
    license_or_permission:
      'Supplied for implementation and technical review; publication permission pending owner confirmation',
    deidentification_status:
      graph || airway
        ? 'Derived from the existing de-identified teaching case; owner verification pending'
        : 'Authored geometry or technical measurements; no patient identifiers added',
    clinical_reviewer: null,
    review_date: null,
    anatomy_profile_id: profile,
    camera_orientation_description:
      landmarks[id] ??
      (teachingProp
        ? 'Authored local millimetres; +Z forward; placement and movable pivots are recorded in devices/teaching-props.json'
        : larynx
          ? 'Patient LPS millimetres; authored forward/left/anterior frame in larynx.json; look along increasing path distance'
          : devices
            ? 'Accessory local millimetres; distal tip at origin; +Z forward; scene places along the scope optical frame'
            : 'Patient LPS millimetres; buildTransportFrames with the graph orientation landmarks; 88 degree nominal field of view across the wider optical axis'),
    approved_use:
      'Development and technical review of educational simulation assets; clinical review and publication decision pending',
    clinical_review_status: 'pending',
    publication_permitted: null,
  })
}
const manifest = {
  schema: 'bronchoscopy_foundations_scope_assets/v1',
  anatomy_profile_id: profile,
  files,
  payloadBytes: files.reduce((sum, entry) => sum + entry.bytes, 0),
  totalBudgetBytes: 8_000_000,
  manifestHashPolicy:
    'Every asset except this self-describing manifest is listed; budgets include this manifest.',
  releaseStatus: 'pending-clinical-review-and-junction-decision',
  unresolved: [
    'The authored larynx exit ring is not continuous with the unchanged capped source inlet. See review/device-review.json and the asset documentation.',
  ],
}
const text = await prettier.format(JSON.stringify(manifest), { ...options, parser: 'json' })
if (manifest.payloadBytes + Buffer.byteLength(text) > manifest.totalBudgetBytes)
  throw new Error('Anatomy total budget exceeded')
await writeFile(path.join(anatomy, 'manifest.json'), text)
console.log(
  `Manifest: ${files.length} assets; ${manifest.payloadBytes + Buffer.byteLength(text)} bytes including manifest.`,
)
